"""Eval harness: does retrieval actually work, measured against hand labels.

The unit of truth is a labeled pair: a query and the postings a human says should
come back. Nothing here is generated by a model — a model grading its own
retrieval is not evidence.

Metrics:
  hit@k   — fraction of queries where at least one correct posting is in the top k
  MRR     — mean of 1/rank of the first correct posting (rewards putting it first)
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path

import psycopg

from .search import search as run_search

DEFAULT_LABELS = Path(__file__).resolve().parents[2] / "evals" / "labels.json"


@dataclass(frozen=True)
class Label:
    id: str
    query: str
    target_ids: tuple[int, ...]


def load_labels(path: Path = DEFAULT_LABELS) -> list[Label]:
    payload = json.loads(Path(path).read_text())
    labels: list[Label] = []
    for entry in payload.get("labels", []):
        targets = tuple(int(t) for t in entry.get("target_ids", []))
        if not targets:
            continue  # an unlabeled query is not a data point
        labels.append(Label(id=str(entry["id"]), query=entry["query"], target_ids=targets))
    return labels


def first_hit_rank(ranked_ids: list[int], target_ids: set[int]) -> int | None:
    """1-based rank of the first correct posting, or None if none were retrieved."""
    for i, pid in enumerate(ranked_ids, 1):
        if pid in target_ids:
            return i
    return None


def hit_at(rank: int | None, k: int) -> bool:
    return rank is not None and rank <= k


def reciprocal_rank(rank: int | None) -> float:
    return 0.0 if rank is None else 1.0 / rank


def summarise(rows: list[dict]) -> dict:
    """rows: [{"query":..., "rank": int|None}] -> aggregate metrics."""
    n = len(rows)
    if n == 0:
        return {"n": 0, "hit@5": 0.0, "hit@10": 0.0, "mrr": 0.0}
    return {
        "n": n,
        "hit@5": round(sum(1 for r in rows if hit_at(r["rank"], 5)) / n, 4),
        "hit@10": round(sum(1 for r in rows if hit_at(r["rank"], 10)) / n, 4),
        "mrr": round(sum(reciprocal_rank(r["rank"]) for r in rows) / n, 4),
    }


def evaluate(
    conn: psycopg.Connection,
    embedder,
    labels: list[Label],
    modes: tuple[str, ...] = ("semantic", "lexical", "hybrid"),
) -> dict:
    """Run every labeled query under each retrieval mode and score the ranking."""
    runs: dict[str, list[dict]] = {}
    for name in modes:
        rows: list[dict] = []
        for label in labels:
            hits = run_search(conn, embedder, label.query, k=10, mode=name)
            ranked = [int(h["id"]) for h in hits]
            rank = first_hit_rank(ranked, set(label.target_ids))
            rows.append(
                {
                    "id": label.id,
                    "query": label.query,
                    "rank": rank,
                    "top1": hits[0]["title"] if hits else "",
                }
            )
        runs[name] = rows
    return {
        "metrics": {name: summarise(rows) for name, rows in runs.items()},
        "detail": runs,
    }


def render(result: dict) -> str:
    lines = []
    for name, m in result["metrics"].items():
        lines.append(
            f"{name:<10} n={m['n']:<3} hit@5={m['hit@5']:.3f}  hit@10={m['hit@10']:.3f}  MRR={m['mrr']:.3f}"
        )
    best = max(result["metrics"], key=lambda m: result["metrics"][m]["hit@5"], default=None)
    if best and result["metrics"][best]["n"]:
        lines.append(f"\nbest hit@5: {best}")
    misses = [r for r in result["detail"].get("semantic", []) if r["rank"] is None]
    if misses:
        lines.append(f"\nsemantic misses ({len(misses)}):")
        for r in misses[:8]:
            lines.append(f"  {r['id']} '{r['query'][:40]}' -> {r['top1'][:38]}")
    return "\n".join(lines)
